'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const e=require('../src/engine.js');
const root=path.join(__dirname,'..');
const rows=e.readCsv(fs.readFileSync(path.join(__dirname,'fixtures','life_2026_operations.csv'),'utf8'));
const annotations=JSON.parse(fs.readFileSync(path.join(__dirname,'fixtures','life_2026_annotations.json'),'utf8'));
const example=()=>e.mergeAnnotations(rows,annotations);
const at='2026-10-25',until='2027-12-31';
const near=(a,b)=>assert.ok(Math.abs(a-b)<0.011,`${a} doit valoir ${b}`);
test('par défaut, aucune désactivation et sommes globales inchangées',()=>{
 const m=example();assert.deepEqual(e.excludedAccountNames(m),[]);
 const individual=e.cashAccountNames(m).map(name=>e.totalBalance(m,at,name));
 near(e.totalBalance(m,at),individual.reduce((a,b)=>a+b,0));
 const before=e.forecast(m,at,until);
 m.excludedAccounts=[];
 assert.deepEqual(e.forecast(m,at,until),before);
});
test('exclure 2 comptes : global = somme des 2 autres, comptes exclus toujours consultables',()=>{
 const m=example(),before=JSON.stringify(m),cash=e.cashAccountNames(m);
 assert.deepEqual(cash,['BPS','BoursoBank','Qonto','Revolut']);
 const snapshots=Object.fromEntries(cash.map(a=>[a,e.forecast(m,at,until,a)]));
 m.excludedAccounts=['Qonto','BPS'];
 assert.deepEqual(e.includedAccountNames(m),['BoursoBank','Revolut']);
 assert.deepEqual(e.excludedAccountNames(m),['BPS','Qonto']);
 const inc=['BoursoBank','Revolut'];
 near(e.totalBalance(m,at),inc.reduce((n,a)=>n+snapshots[a].opening,0));
 near(e.forecast(m,at,until).closing,inc.reduce((n,a)=>n+snapshots[a].closing,0));
 for(const name of cash)assert.deepEqual(e.forecast(m,at,until,name),snapshots[name]);
 assert.ok(before.length>0);
});
test('règle récurrente et opération prévue du compte désactivé : exclues du global seulement',()=>{
 const m=example(),original=e.forecast(m,at,'2026-12-31');
 const chosen='BoursoBank';
 m.excludedAccounts=[chosen];
 const remainder=e.cashAccountNames(m).filter(c=>c!==chosen);
 const expected=remainder.reduce((s,account)=>s+e.forecast(m,at,'2026-12-31',account).closing,0);
 near(e.forecast(m,at,'2026-12-31').closing,expected);
 assert.notEqual(e.forecast(m,at,'2026-12-31').closing,original.closing);
 assert.ok(e.recurrencePreview(m,at,'2026-12-31',chosen).length>0);
});
test('tout désactivé : global zéro, chaque solde individuel et audit conservés',()=>{
 const m=example(),before=e.auditCsv(e.auditOperations(m,{scope:'all',at,until}));
 m.excludedAccounts=e.cashAccountNames(m);
 assert.deepEqual(e.includedAccountNames(m),[]);
 assert.equal(e.totalBalance(m,at),0);
 assert.equal(e.forecast(m,at,until).opening,0);
 assert.equal(e.forecast(m,at,until).closing,0);
 assert.equal(e.forecast(m,at,until).events.length,0);
 assert.ok(e.totalBalance(m,at,'BPS')!==null);
 assert.equal(e.auditCsv(e.auditOperations(m,{scope:'all',at,until})),before);
 assert.equal(e.recurrencePreview(m,at,until).length,e.auditOperations(m,{scope:'all',at,until}).filter(r=>r.origine==='recurrence').length);
});
test('import/export conserve les comptes désactivés sans changer les écritures',()=>{
 const m=example();m.excludedAccounts=['BPS','Qonto'];
 const exported=JSON.parse(JSON.stringify({notes:m.notes,rules:m.rules,accounts:m.accounts,excludedAccounts:m.excludedAccounts,references:m.references,manualRows:m.rows.filter(r=>r.manual)}));
 const restored=e.mergeAnnotations(rows,exported);
 assert.deepEqual(restored,m);
 assert.deepEqual(e.excludedAccountNames(restored),['BPS','Qonto']);
 const old=e.mergeAnnotations(rows,{...exported,excludedAccounts:undefined});
 assert.deepEqual(e.excludedAccountNames(old),[]);
});
test('interface : cases comptes, chart x+1, édition indépendante, réorganisation persistante',()=>{
 const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
 for(const id of ['accountToggles','dashboard','resetLayout'])assert.match(html,new RegExp(`id="${id}"`));
 assert.match(html,/QBudgetEngine\.excludedAccountNames\(model\)\.forEach/);
 assert.match(html,/QBudgetEngine\.includedAccountNames\(model\)/);
 assert.match(html,/name:account\+' \(hors cumul\)'/);
 assert.match(html,/layout-grip/);
 assert.match(html,/dragstart/);
 assert.match(html,/dragover/);
 assert.match(html,/drop'/);
 assert.match(html,/localStorage\.setItem\(LAYOUT_KEY/);
 assert.match(html,/localStorage\.removeItem\(LAYOUT_KEY/);
 assert.match(html,/excludedAccounts:model\.excludedAccounts/);
 assert.match(html,/model\.excludedAccounts=o\.excludedAccounts\|\|\[\]/);
});
